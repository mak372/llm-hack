"""Publish a verified fix as a GitHub pull request.

This is the agent's outward action: once a fix is VERIFIED (re-attack fails,
good path holds), it opens a PR carrying the patch, the generated regression
tests, and the evidence report. The PR is grounded in truthful sources -- the
body states each claim was confirmed by a deterministic re-attack, not by an
LLM's say-so.

The PR is opened via the GitHub REST API using GITHUB_TOKEN (no `gh` needed),
so it works as an autonomous, API-driven action. Pushing/PR creation only
happens when `push=True`; otherwise it stops at a local branch + commit and
writes the PR body to a file for review.
"""

from __future__ import annotations

import datetime
import os
import re
import subprocess
from dataclasses import dataclass

from engine.remediate import RemediationResult


@dataclass
class PRResult:
    branch: str
    committed: bool
    pushed: bool
    pr_url: str = ""
    body_path: str = ""
    base_branch: str = "main"
    owner_repo: str = ""


class PublishError(RuntimeError):
    pass


def _git(cwd: str, *args: str, check: bool = True) -> str:
    proc = subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True)
    if check and proc.returncode != 0:
        raise PublishError(f"git {' '.join(args)} failed: {proc.stderr.strip()}")
    return proc.stdout.strip()


def remote_owner_repo(cwd: str) -> tuple[str, str] | None:
    """Parse 'owner/repo' from the origin remote URL, or None if no remote."""
    try:
        url = _git(cwd, "remote", "get-url", "origin")
    except PublishError:
        return None
    m = re.search(r"github\.com[:/]([^/]+)/(.+?)(?:\.git)?$", url)
    return (m.group(1), m.group(2)) if m else None


def build_pr_body(results: list[RemediationResult], base_url: str) -> str:
    """Markdown PR body: what was fixed and the truthful evidence behind it."""
    verified = [r for r in results if r.verified]
    now = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
    lines = [
        "## Autonomous security fix — verified by re-attack",
        "",
        f"The attack-fix-verify agent found and fixed {len(verified)} "
        f"vulnerabilit{'y' if len(verified) == 1 else 'ies'} in `{base_url}`.",
        "",
        "**Every fix below was confirmed by a deterministic re-attack, not by an "
        "LLM judgement.** A fix is included only if, on the patched code: the "
        "original exploit now fails, the legitimate good path still works, and the "
        "app still starts.",
        "",
        "| Vulnerability | Endpoint | Re-attack blocked | Good path | Attempts |",
        "|---|---|:--:|:--:|:--:|",
    ]
    for r in verified:
        f = r.finding
        last = r.attempts[-1].verify
        lines.append(
            f"| {f.vuln_class} | `{f.endpoint}` | "
            f"{'✅' if last.attack_blocked else '❌'} | "
            f"{'✅' if last.good_path_ok else '❌'} | {len(r.attempts)} |")
    lines.append("")
    for r in verified:
        f = r.finding
        lines += [
            f"### {f.vuln_class} — `{f.method} {f.endpoint}`",
            "",
            f"- **Evidence:** {f.detail}",
            f"- **Reproduce:** `{f.curl}`",
            "",
            "```diff",
            r.diff.rstrip(),
            "```",
            "",
        ]
    lines += [
        "Regression tests for each fix are included in this PR and will fail if the "
        "vulnerability is reintroduced.",
        "",
        f"<sub>Generated by the attack-fix-verify agent at {now}.</sub>",
    ]
    return "\n".join(lines)


def open_pull_request(
    repo_dir: str,
    results: list[RemediationResult],
    files_to_add: list[str],
    title: str,
    body: str,
    base_branch: str = "main",
    branch: str | None = None,
    push: bool = False,
    token: str | None = None,
) -> PRResult:
    """Create a fix branch, commit the given files, and (optionally) push + open a PR.

    The working tree is expected to already contain the applied patches; this
    function only branches, stages the named files (force-added so report/tests
    that are gitignored in the main tree still land in the PR), and commits.
    """
    token = token or os.environ.get("GITHUB_TOKEN")
    if branch is None:
        branch = "afv/fix-" + datetime.datetime.now().strftime("%Y%m%d-%H%M%S")

    _git(repo_dir, "checkout", "-b", branch)
    for path in files_to_add:
        if os.path.exists(os.path.join(repo_dir, path)) or os.path.isabs(path):
            _git(repo_dir, "add", "-f", path)
    _git(repo_dir, "commit", "-m", title, "-m",
         "Each fix was verified by re-running the original attack against the "
         "patched code (deterministic, not LLM-judged).")

    result = PRResult(branch=branch, committed=True, pushed=False, base_branch=base_branch)

    owner_repo = remote_owner_repo(repo_dir)
    result.owner_repo = "/".join(owner_repo) if owner_repo else ""

    body_path = os.path.join(repo_dir, "PR_BODY.md")
    with open(body_path, "w", encoding="utf-8") as fh:
        fh.write(body)
    result.body_path = body_path

    if not push:
        return result

    if not owner_repo:
        raise PublishError("push requested but no GitHub 'origin' remote is configured")
    if not token:
        raise PublishError("push requested but GITHUB_TOKEN is not set")

    owner, repo = owner_repo
    push_url = f"https://x-access-token:{token}@github.com/{owner}/{repo}.git"
    _git(repo_dir, "push", push_url, f"{branch}:{branch}")  # token never logged
    result.pushed = True
    result.pr_url = _create_pr_via_api(owner, repo, branch, base_branch, title, body, token)
    return result


def _create_pr_via_api(owner: str, repo: str, head: str, base: str,
                       title: str, body: str, token: str) -> str:
    import httpx
    resp = httpx.post(
        f"https://api.github.com/repos/{owner}/{repo}/pulls",
        headers={"Authorization": f"Bearer {token}",
                 "Accept": "application/vnd.github+json",
                 "X-GitHub-Api-Version": "2022-11-28"},
        json={"title": title, "head": head, "base": base, "body": body},
        timeout=30.0,
    )
    if resp.status_code >= 300:
        raise PublishError(f"GitHub PR creation failed ({resp.status_code}): {resp.text}")
    return resp.json().get("html_url", "")
