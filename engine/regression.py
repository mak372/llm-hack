"""Generate pytest regression tests from verified fixes.

For each vulnerability we verified as fixed, we emit a standalone pytest file
that re-encodes the attack AND the good path. These are permanent: if someone
later reintroduces the bug, CI fails. The tests run against target_app/app.py,
so they pass only once the fix is actually applied to it (cli --apply).
"""

from __future__ import annotations

import os

from engine.remediate import RemediationResult

_HEADER = '''"""AUTO-GENERATED regression test for {title}.

Generated by the attack-fix-verify tool from a verified fix. It asserts the
original attack is blocked AND the legitimate good path still works.
"""

import sys
from pathlib import Path

import httpx
import pytest

# Find the repo root (the dir containing target_app/) regardless of where this
# generated file lives, and put it on the path.
for _p in Path(__file__).resolve().parents:
    if (_p / "target_app" / "app.py").exists():
        sys.path.insert(0, str(_p))
        break

from target_app.app import app as flask_app, init_db  # noqa: E402


@pytest.fixture()
def client():
    init_db()
    transport = httpx.WSGITransport(app=flask_app)
    with httpx.Client(transport=transport, base_url="http://regression") as c:
        yield c


def _token(client, username, password):
    r = client.post("/login", json={{"username": username, "password": password}})
    assert r.status_code == 200
    return r.json()["token"]
'''

_BODIES = {
    "idor": '''

def test_bob_cannot_read_alice_invoice(client):
    bob = _token(client, "bob", "bob-pw")
    r = client.get("/invoices/101", headers={"Authorization": f"Bearer {bob}"})
    assert r.status_code in (403, 404), "Bob must not read Alice's invoice"


def test_alice_can_still_read_her_own_invoice(client):
    alice = _token(client, "alice", "alice-pw")
    r = client.get("/invoices/101", headers={"Authorization": f"Bearer {alice}"})
    assert r.status_code == 200 and r.json()["owner_id"] == 1
''',
    "sqli": '''

def test_sqli_payload_cannot_leak_other_rows(client):
    alice = _token(client, "alice", "alice-pw")
    r = client.get("/invoices/search", params={"q": "' OR 1=1 -- "},
                   headers={"Authorization": f"Bearer {alice}"})
    assert r.status_code == 200
    for row in r.json():
        assert row["owner_id"] == 1, "injection must not return other users' rows"


def test_alice_can_still_search_her_own_invoices(client):
    alice = _token(client, "alice", "alice-pw")
    r = client.get("/invoices/search", params={"q": "coffee"},
                   headers={"Authorization": f"Bearer {alice}"})
    assert r.status_code == 200 and len(r.json()) == 1
''',
    "data_exposure": '''

def test_me_does_not_expose_sensitive_fields(client):
    alice = _token(client, "alice", "alice-pw")
    r = client.get("/me", headers={"Authorization": f"Bearer {alice}"})
    assert r.status_code == 200
    body = r.json()
    for forbidden in ("password_hash", "token", "reset_token", "ssn"):
        assert forbidden not in body, f"{forbidden} must not be returned"
    assert body["username"] == "alice"
''',
    "missing_auth": '''

def test_admin_users_requires_authentication(client):
    r = client.get("/admin/users")
    assert r.status_code in (401, 403), "must reject unauthenticated callers"


def test_admin_can_still_list_users(client):
    admin = _token(client, "admin", "admin-pw")
    r = client.get("/admin/users", headers={"Authorization": f"Bearer {admin}"})
    assert r.status_code == 200 and len(r.json()) == 3
''',
}

_FILENAMES = {
    "idor": "test_regression_idor.py",
    "sqli": "test_regression_sqli.py",
    "data_exposure": "test_regression_data_exposure.py",
    "missing_auth": "test_regression_missing_auth.py",
}

_TITLES = {
    "idor": "broken access control (IDOR)",
    "sqli": "SQL injection",
    "data_exposure": "sensitive data exposure",
    "missing_auth": "missing authentication",
}


def generate_regression_tests(results: list[RemediationResult], out_dir: str) -> list[str]:
    """Write a regression test file for each verified result. Returns file paths."""
    os.makedirs(out_dir, exist_ok=True)
    written: list[str] = []
    for r in results:
        if not r.verified:
            continue
        vc = r.finding.vuln_class
        if vc not in _BODIES:
            continue
        content = _HEADER.format(title=_TITLES[vc]) + _BODIES[vc]
        path = os.path.join(out_dir, _FILENAMES[vc])
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(content)
        written.append(path)
    return written
